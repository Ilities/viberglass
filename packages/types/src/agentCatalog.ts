import agentPluginCatalog from './agentPluginCatalog.json'
import {
  readHarnessConfigEditor,
  readSettingFields,
  type AgentSettingField,
  type HarnessConfigEditor,
} from './agentSettings'
import { readAgentSignIn, readSignInMethods, type AgentSignIn, type AgentSignInMethod } from './agentSignIn'
import type { AgentType } from './clanker'
import { isClankerConfigV1, type ClankerConfigV1 } from './clankerConfig'

/** A harness this build includes, as its plugin describes it. */
export interface AgentCatalogEntry {
  agent: AgentType
  label: string
  description: string
  /** Path the frontend serves the logo from. */
  logo: string | null
  /** New runners get this harness unless they choose another. */
  isDefault: boolean
  /** Only for tests: accepted, never offered. */
  testOnly: boolean
  /** Harnesses with a lower rank run a custom endpoint first; null ones come last. */
  endpointRank: number | null
  /** What the runner form shows for this harness, besides its model key. */
  settings: AgentSettingField[]
  harnessConfigEditor: HarnessConfigEditor | null
  /** Interactive sign-ins besides API keys. */
  signInMethods: AgentSignInMethod[]
  /** Why it can't run on Lambda; null when it can. */
  lambdaUnsupportedReason: string | null
  /** Added to a "Model key rejected" failure; null when there's nothing to add. */
  rejectedKeyNote: string | null
}

function toEntry(entry: (typeof agentPluginCatalog)[number]): AgentCatalogEntry {
  return {
    agent: entry.agent,
    label: entry.label,
    description: entry.description,
    logo: entry.logo,
    isDefault: entry.default,
    testOnly: entry.testOnly,
    endpointRank: entry.endpointRank,
    settings: readSettingFields(entry.settings),
    harnessConfigEditor: readHarnessConfigEditor(entry.harnessConfigEditor),
    signInMethods: readSignInMethods(entry.signInMethods),
    lambdaUnsupportedReason: entry.lambdaUnsupportedReason ?? null,
    rejectedKeyNote: entry.rejectedKeyNote ?? null,
  }
}

/** The harnesses in this build, in the order the build config lists them. Generated by `npm run generate:catalog`. */
export const AGENT_CATALOG: readonly AgentCatalogEntry[] = agentPluginCatalog.map(toEntry)

const catalogByAgent = new Map<string, AgentCatalogEntry>(AGENT_CATALOG.map((entry) => [entry.agent, entry]))

export function getAgentCatalogEntry(agent: string): AgentCatalogEntry | undefined {
  return catalogByAgent.get(agent)
}

/** The harnesses this build includes; new runners can only use these. */
export const AVAILABLE_AGENT_TYPES: AgentType[] = AGENT_CATALOG.map((entry) => entry.agent)

export function isAvailableAgentType(agent: string): boolean {
  return catalogByAgent.has(agent)
}

/** The settings a harness takes; none for one left out of this build. */
export function getAgentSettingFields(agent: string): AgentSettingField[] {
  return getAgentCatalogEntry(agent)?.settings ?? []
}

export function getHarnessConfigEditor(agent: string): HarnessConfigEditor | null {
  return getAgentCatalogEntry(agent)?.harnessConfigEditor ?? null
}

export function getAgentSignInMethods(agent: string): AgentSignInMethod[] {
  return getAgentCatalogEntry(agent)?.signInMethods ?? []
}

/** Why a harness can't run on a deployment strategy, by the strategy's name; null when it can. */
export function agentStrategyUnsupportedReason(agent: string, strategyName: string | null | undefined): string | null {
  const strategy = (strategyName ?? '').trim().toLowerCase()
  if (strategy !== 'lambda' && strategy !== 'aws-lambda-container') return null
  return getAgentCatalogEntry(agent)?.lambdaUnsupportedReason ?? null
}

/** A runner's interactive sign-in and its method, when the runner chose one its harness declares. */
export interface RunnerSignIn {
  signIn: AgentSignIn
  method: AgentSignInMethod
}

export function getRunnerSignIn(deploymentConfig: unknown): RunnerSignIn | null {
  const agent: ClankerConfigV1['agent'] | undefined = isClankerConfigV1(deploymentConfig) ? deploymentConfig.agent : undefined
  const signIn = agent ? readAgentSignIn(agent.signIn) : undefined
  const method = signIn && agent ? getAgentSignInMethods(agent.type).find((candidate) => candidate.id === signIn.method) : undefined
  return signIn && method ? { signIn, method } : null
}

function findDefaultAgent(): AgentType {
  const entry = AGENT_CATALOG.find((candidate) => candidate.isDefault)
  if (!entry) throw new Error('The agent catalog has no default harness. Check defaultAgent in viberglass.plugins.json.')
  return entry.agent
}

export const DEFAULT_AGENT_TYPE: AgentType = findDefaultAgent()

export const AGENT_LABELS: Readonly<Record<string, string>> = Object.fromEntries(
  AGENT_CATALOG.map((entry) => [entry.agent, entry.label]),
)

export function isTestOnlyAgent(agent: string): boolean {
  return getAgentCatalogEntry(agent)?.testOnly === true
}

export interface AgentOption {
  value: AgentType
  label: string
  description: string
  logo: string | null
}

/** The harnesses a person can pick for a runner. */
export const AGENT_OPTIONS: AgentOption[] = AGENT_CATALOG.filter((entry) => !entry.testOnly).map((entry) => ({
  value: entry.agent,
  label: entry.label,
  description: entry.description,
  logo: entry.logo,
}))

/** A harness left out of this build shows as its id. */
export function getAgentLabel(agent?: string | null): string {
  return AGENT_LABELS[agent || DEFAULT_AGENT_TYPE] ?? agent ?? DEFAULT_AGENT_TYPE
}
